#!/usr/bin/env bash
set -Eeuo pipefail

APP_DOMAIN="mymarket.pbo.web.id"
LETSENCRYPT_EMAIL=""
ENABLE_HTTPS=1
RESET_DEMO_DATA=0
DOMAIN_EXPLICIT=0
EMAIL_EXPLICIT=0
ORIGINAL_ARGS=("$@")

usage() {
    cat <<'EOF'
Penggunaan:
  sudo bash deploy/setup-production.sh [opsi]

Opsi:
  --domain DOMAIN       Domain production (default: mymarket.pbo.web.id)
  --email EMAIL         Email Let's Encrypt
  --skip-https          Siapkan HTTP saja tanpa meminta sertifikat
  --reset-demo          Hapus/isi ulang data operasional dengan data demo
  -h, --help            Tampilkan bantuan

Script aman dijalankan ulang setelah `git pull`. Database dan secret yang sudah
ada dipertahankan, kecuali --reset-demo diberikan secara eksplisit.
EOF
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --domain)
            [[ $# -ge 2 ]] || { echo "Nilai --domain belum diisi." >&2; exit 2; }
            APP_DOMAIN="$2"
            DOMAIN_EXPLICIT=1
            shift 2
            ;;
        --email)
            [[ $# -ge 2 ]] || { echo "Nilai --email belum diisi." >&2; exit 2; }
            LETSENCRYPT_EMAIL="$2"
            EMAIL_EXPLICIT=1
            shift 2
            ;;
        --skip-https)
            ENABLE_HTTPS=0
            shift
            ;;
        --reset-demo)
            RESET_DEMO_DATA=1
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "Opsi tidak dikenal: $1" >&2
            usage >&2
            exit 2
            ;;
    esac
done

if [[ ${EUID} -ne 0 ]]; then
    exec sudo -E bash "$0" "${ORIGINAL_ARGS[@]}"
fi

if [[ ! "$APP_DOMAIN" =~ ^[A-Za-z0-9.-]+$ ]]; then
    echo "Domain tidak valid: ${APP_DOMAIN}" >&2
    exit 2
fi
APP_SCHEME="https"
[[ $ENABLE_HTTPS -eq 1 ]] || APP_SCHEME="http"

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd -- "${SCRIPT_DIR}/.." && pwd)"
BACK_DIR="${REPO_DIR}/back"
FRONT_DIR="${REPO_DIR}/front"
CONFIG_DIR="/etc/mymarket"
LOG_DIR="/var/log/mymarket"
BACKUP_DIR="/var/backups/mymarket"
BACKEND_ENV="${CONFIG_DIR}/backend.env"
DEPLOY_ENV="${CONFIG_DIR}/deployment.env"
VENV_DIR="${BACK_DIR}/.venv-production"
SUPERVISOR_CONFIG="/etc/supervisor/conf.d/mymarket.conf"
NGINX_SITE="/etc/nginx/sites-available/mymarket"

APP_USER="${SUDO_USER:-mymarket}"
if [[ "$APP_USER" == "root" ]] && id mymarket >/dev/null 2>&1; then
    APP_USER="mymarket"
fi
if ! id "$APP_USER" >/dev/null 2>&1; then
    echo "User aplikasi '$APP_USER' tidak ditemukan." >&2
    exit 1
fi
APP_GROUP="$(id -gn "$APP_USER")"
APP_HOME="$(getent passwd "$APP_USER" | cut -d: -f6)"

required_commands=(
    certbot curl git mariadb mariadb-admin mariadb-dump mariadbd mariadbd-safe
    mariadb-install-db
    nginx node npm python3 sudo supervisorctl supervisord
)
missing_commands=()
for command_name in "${required_commands[@]}"; do
    command -v "$command_name" >/dev/null 2>&1 || missing_commands+=("$command_name")
done
if [[ ${#missing_commands[@]} -gt 0 ]]; then
    echo "Paket server belum lengkap. Command yang hilang: ${missing_commands[*]}" >&2
    exit 1
fi

node_version="$(node -p 'process.versions.node')"
if ! node -e "const [a,b]=process.versions.node.split('.').map(Number); process.exit(a>20 || (a===20 && b>=9) ? 0 : 1)"; then
    echo "Node.js ${node_version} terlalu lama. Next.js memerlukan Node >= 20.9." >&2
    exit 1
fi

install -d -m 0750 -o root -g "$APP_GROUP" "$CONFIG_DIR"
install -d -m 0775 -o "$APP_USER" -g "$APP_GROUP" "$LOG_DIR" "$BACKUP_DIR"
install -d -m 0755 /run/mysqld
chown mysql:mysql /run/mysqld /var/lib/mysql

DB_NAME="kasir_pbo"
DB_USER="mymarket_app"
DB_PASSWORD=""
GEMINI_API_KEY=""

if [[ -f "$BACKEND_ENV" ]]; then
    # This file is root-owned and was generated by this script.
    set -a
    # shellcheck disable=SC1090
    source "$BACKEND_ENV"
    set +a
fi

if [[ -z "${DB_PASSWORD:-}" ]]; then
    DB_PASSWORD="$(python3 - <<'PY'
import secrets
import string

alphabet = string.ascii_letters + string.digits
print("".join(secrets.choice(alphabet) for _ in range(40)))
PY
)"
fi

if [[ -f "$DEPLOY_ENV" ]]; then
    requested_domain="$APP_DOMAIN"
    requested_email="$LETSENCRYPT_EMAIL"
    # shellcheck disable=SC1090
    source "$DEPLOY_ENV"
    [[ $DOMAIN_EXPLICIT -eq 0 ]] || APP_DOMAIN="$requested_domain"
    [[ $EMAIL_EXPLICIT -eq 0 ]] || LETSENCRYPT_EMAIL="$requested_email"
fi

if [[ -z "${GEMINI_API_KEY:-}" && -t 0 ]]; then
    read -r -s -p "Gemini API key (Enter untuk melewati): " GEMINI_API_KEY
    echo
fi
if [[ $ENABLE_HTTPS -eq 1 && -z "$LETSENCRYPT_EMAIL" && -t 0 ]]; then
    read -r -p "Email Let's Encrypt: " LETSENCRYPT_EMAIL
fi

umask 077
cat > "$BACKEND_ENV" <<EOF
APP_ENV=production
ALLOW_DEV_ACTOR_HEADER=false
DATABASE_URL=mysql+pymysql://${DB_USER}:${DB_PASSWORD}@127.0.0.1:3306/${DB_NAME}?charset=utf8mb4
CORS_ORIGINS=https://${APP_DOMAIN},http://${APP_DOMAIN}
GEMINI_API_KEY=${GEMINI_API_KEY:-}
GEMINI_MODEL=gemini-3.5-flash-lite
GEMINI_FALLBACK_MODEL=gemini-3.6-flash
GEMINI_TIMEOUT_SECONDS=12
GEMINI_RETRY_ATTEMPTS=1
GOOGLE_CLOUD_PROJECT_NAME=projek-pbo
GOOGLE_CLOUD_PROJECT_NUMBER=69198748984
BUSINESS_TIMEZONE=Asia/Makassar
EOF
cat > "$DEPLOY_ENV" <<EOF
APP_DOMAIN=${APP_DOMAIN}
LETSENCRYPT_EMAIL=${LETSENCRYPT_EMAIL}
DB_NAME=${DB_NAME}
DB_USER=${DB_USER}
DB_PASSWORD=${DB_PASSWORD}
EOF
chown root:"$APP_GROUP" "$BACKEND_ENV" "$DEPLOY_ENV"
chmod 0640 "$BACKEND_ENV" "$DEPLOY_ENV"
umask 022

cat > "${CONFIG_DIR}/mysql-client.cnf" <<EOF
[client]
host=127.0.0.1
user=${DB_USER}
password=${DB_PASSWORD}
EOF
chown root:"$APP_GROUP" "${CONFIG_DIR}/mysql-client.cnf"
chmod 0640 "${CONFIG_DIR}/mysql-client.cnf"

start_mariadb_for_setup() {
    if mariadb-admin ping --silent >/dev/null 2>&1; then
        return
    fi
    if [[ ! -d /var/lib/mysql/mysql ]]; then
        mariadb-install-db --user=mysql --datadir=/var/lib/mysql
    fi
    chown -R mysql:mysql /var/lib/mysql
    if command -v service >/dev/null 2>&1; then
        service mariadb start >/dev/null 2>&1 || true
    fi
    if ! mariadb-admin ping --silent >/dev/null 2>&1; then
        nohup mariadbd-safe --user=mysql --datadir=/var/lib/mysql \
            >"${LOG_DIR}/mariadb-bootstrap.log" 2>&1 &
    fi
    for _ in $(seq 1 30); do
        mariadb-admin ping --silent >/dev/null 2>&1 && return
        sleep 1
    done
    echo "MariaDB gagal dijalankan. Periksa ${LOG_DIR}/mariadb-bootstrap.log" >&2
    exit 1
}

start_mariadb_for_setup

mariadb --protocol=socket -uroot <<SQL
CREATE DATABASE IF NOT EXISTS \`${DB_NAME}\`
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${DB_USER}'@'127.0.0.1' IDENTIFIED BY '${DB_PASSWORD}';
ALTER USER '${DB_USER}'@'127.0.0.1' IDENTIFIED BY '${DB_PASSWORD}';
GRANT ALL PRIVILEGES ON \`${DB_NAME}\`.* TO '${DB_USER}'@'127.0.0.1';
FLUSH PRIVILEGES;
SQL

chown -R "$APP_USER:$APP_GROUP" "$REPO_DIR"

run_as_app() {
    sudo -u "$APP_USER" -H env HOME="$APP_HOME" "$@"
}

run_backend_as_app() {
    sudo -u "$APP_USER" -H bash -c '
        env_file=$1
        work_dir=$2
        shift 2
        set -a
        source "$env_file"
        set +a
        cd "$work_dir"
        exec "$@"
    ' bash "$BACKEND_ENV" "$BACK_DIR" "$@"
}

if [[ ! -x "${VENV_DIR}/bin/python" ]]; then
    run_as_app python3 -m venv "$VENV_DIR"
fi
run_as_app "${VENV_DIR}/bin/python" -m pip install --upgrade pip
run_as_app "${VENV_DIR}/bin/python" -m pip install -r "${BACK_DIR}/requirements.txt"

run_backend_as_app "${VENV_DIR}/bin/python" -m alembic upgrade head
product_count="$(mariadb --defaults-extra-file="${CONFIG_DIR}/mysql-client.cnf" \
    --batch --skip-column-names "$DB_NAME" \
    -e 'SELECT COUNT(*) FROM products;' 2>/dev/null || printf '0')"
database_was_empty=0
[[ "$product_count" == "0" ]] && database_was_empty=1

run_backend_as_app "${VENV_DIR}/bin/python" -m app.seed

if [[ $RESET_DEMO_DATA -eq 1 || $database_was_empty -eq 1 ]]; then
    run_backend_as_app \
        "${VENV_DIR}/bin/python" -m app.demo_seed --reset --no-backup
fi

(
    cd "$FRONT_DIR"
    run_as_app env \
        NEXT_PUBLIC_API_URL=/api/v1 \
        NEXT_PUBLIC_ADMIN_ACTOR_CODE=KASIR03 \
        NEXT_PUBLIC_ALLOW_DEV_ACTOR=false \
        NEXT_PUBLIC_APP_URL="${APP_SCHEME}://${APP_DOMAIN}" \
        npm ci
    run_as_app env \
        NEXT_PUBLIC_API_URL=/api/v1 \
        NEXT_PUBLIC_ADMIN_ACTOR_CODE=KASIR03 \
        NEXT_PUBLIC_ALLOW_DEV_ACTOR=false \
        NEXT_PUBLIC_APP_URL="${APP_SCHEME}://${APP_DOMAIN}" \
        npm run build
    install -d -m 0755 -o "$APP_USER" -g "$APP_GROUP" .next/standalone/.next
    cp -a public .next/standalone/
    cp -a .next/static .next/standalone/.next/
    chown -R "$APP_USER:$APP_GROUP" .next/standalone
)

cat > /usr/local/sbin/mymarket-mariadb <<'EOF'
#!/usr/bin/env bash
set -Eeuo pipefail
install -d -m 0755 -o mysql -g mysql /run/mysqld
if [[ ! -d /var/lib/mysql/mysql ]]; then
    mariadb-install-db --user=mysql --datadir=/var/lib/mysql
fi
chown -R mysql:mysql /var/lib/mysql
exec /usr/sbin/mariadbd --user=mysql --console
EOF

cat > /usr/local/sbin/mymarket-backend <<EOF
#!/usr/bin/env bash
set -Eeuo pipefail
set -a
source ${BACKEND_ENV}
set +a
cd ${BACK_DIR}
exec ${VENV_DIR}/bin/uvicorn app.main:app --host 127.0.0.1 --port 8000 --workers 1
EOF

cat > /usr/local/sbin/mymarket-frontend <<EOF
#!/usr/bin/env bash
set -Eeuo pipefail
cd ${FRONT_DIR}/.next/standalone
exec env NODE_ENV=production NEXT_TELEMETRY_DISABLED=1 HOSTNAME=127.0.0.1 PORT=3000 node server.js
EOF

cat > /usr/local/sbin/mymarket-certbot-renew <<'EOF'
#!/usr/bin/env bash
set -u
while true; do
    sleep 12h
    certbot renew --quiet --deploy-hook "nginx -s reload" || true
done
EOF
chmod 0755 \
    /usr/local/sbin/mymarket-mariadb \
    /usr/local/sbin/mymarket-backend \
    /usr/local/sbin/mymarket-frontend \
    /usr/local/sbin/mymarket-certbot-renew

cat > "$NGINX_SITE" <<EOF
server {
    listen 80;
    listen [::]:80;
    server_name ${APP_DOMAIN};

    client_max_body_size 32m;

    location /api/ {
        proxy_pass http://127.0.0.1:8000;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_buffering off;
        proxy_read_timeout 120s;
    }

    location / {
        proxy_pass http://127.0.0.1:3000;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_read_timeout 120s;
    }
}
EOF
ln -sfn "$NGINX_SITE" /etc/nginx/sites-enabled/mymarket
rm -f /etc/nginx/sites-enabled/default
nginx -t

cat > "$SUPERVISOR_CONFIG" <<EOF
[group:mymarket]
programs=mymarket-mariadb,mymarket-backend,mymarket-frontend,mymarket-nginx,mymarket-certbot-renew
priority=10

[program:mymarket-mariadb]
command=/usr/local/sbin/mymarket-mariadb
priority=10
autostart=true
autorestart=true
startsecs=5
startretries=20
stopsignal=TERM
stopwaitsecs=60
stdout_logfile=${LOG_DIR}/mariadb.log
stderr_logfile=${LOG_DIR}/mariadb-error.log

[program:mymarket-backend]
command=/usr/local/sbin/mymarket-backend
directory=${BACK_DIR}
user=${APP_USER}
environment=HOME="${APP_HOME}"
priority=20
autostart=true
autorestart=true
startsecs=5
startretries=20
stopasgroup=true
killasgroup=true
stdout_logfile=${LOG_DIR}/backend.log
stderr_logfile=${LOG_DIR}/backend-error.log

[program:mymarket-frontend]
command=/usr/local/sbin/mymarket-frontend
directory=${FRONT_DIR}/.next/standalone
user=${APP_USER}
environment=HOME="${APP_HOME}"
priority=20
autostart=true
autorestart=true
startsecs=5
startretries=20
stopasgroup=true
killasgroup=true
stdout_logfile=${LOG_DIR}/frontend.log
stderr_logfile=${LOG_DIR}/frontend-error.log

[program:mymarket-nginx]
command=/usr/sbin/nginx -g "daemon off;"
priority=30
autostart=true
autorestart=true
startsecs=3
startretries=20
stopsignal=QUIT
stdout_logfile=${LOG_DIR}/nginx.log
stderr_logfile=${LOG_DIR}/nginx-error.log

[program:mymarket-certbot-renew]
command=/usr/local/sbin/mymarket-certbot-renew
priority=40
autostart=true
autorestart=true
startsecs=3
startretries=20
stopsignal=TERM
stdout_logfile=${LOG_DIR}/certbot-renew.log
stderr_logfile=${LOG_DIR}/certbot-renew-error.log
EOF

if supervisorctl status 'mymarket:*' >/dev/null 2>&1; then
    supervisorctl stop 'mymarket:*' >/dev/null 2>&1 || true
fi
if command -v service >/dev/null 2>&1; then
    service nginx stop >/dev/null 2>&1 || true
    service mariadb stop >/dev/null 2>&1 || true
fi

if supervisorctl status >/dev/null 2>&1; then
    supervisorctl reread
    supervisorctl update
else
    supervisord -c /etc/supervisor/supervisord.conf
fi
supervisorctl restart 'mymarket:*' >/dev/null

health_ok=0
for _ in $(seq 1 40); do
    if curl -fsS http://127.0.0.1:8000/health >/dev/null \
        && curl -fsS -H "Host: ${APP_DOMAIN}" http://127.0.0.1/login >/dev/null; then
        health_ok=1
        break
    fi
    sleep 2
done
if [[ $health_ok -ne 1 ]]; then
    supervisorctl status 'mymarket:*' || true
    echo "Aplikasi belum sehat. Periksa log di ${LOG_DIR}." >&2
    exit 1
fi

if [[ $ENABLE_HTTPS -eq 1 ]]; then
    certbot_args=(
        --nginx
        --non-interactive
        --agree-tos
        --redirect
        -d "$APP_DOMAIN"
    )
    if [[ -n "$LETSENCRYPT_EMAIL" ]]; then
        certbot_args+=(--email "$LETSENCRYPT_EMAIL")
    else
        certbot_args+=(--register-unsafely-without-email)
    fi
    certbot "${certbot_args[@]}"
    nginx -t
    nginx -s reload
fi

timestamp="$(date +%Y%m%d-%H%M%S)"
mariadb-dump --defaults-extra-file="${CONFIG_DIR}/mysql-client.cnf" \
    --single-transaction --quick "$DB_NAME" \
    > "${BACKUP_DIR}/initial-${timestamp}.sql"
chmod 0600 "${BACKUP_DIR}/initial-${timestamp}.sql"

echo
echo "MYMARKET berhasil dipasang."
echo "URL             : ${APP_SCHEME}://${APP_DOMAIN}"
echo "Admin           : admin@gmail.com / password"
echo "Kasir utama     : KASIR03 / admin12345"
echo "PIN supervisor  : 123456"
echo "Status          : sudo supervisorctl status 'mymarket:*'"
echo "Log             : ${LOG_DIR}"
echo "Backup awal     : ${BACKUP_DIR}/initial-${timestamp}.sql"
echo
echo "Segera ganti password dan PIN awal setelah login."
if [[ "$(cat /proc/1/comm 2>/dev/null || true)" != "supervisord" ]]; then
    echo "PERINGATAN: PID 1 container bukan supervisord. Minta admin memakai"
    echo "deploy/server-image/Dockerfile agar seluruh service otomatis hidup kembali"
    echo "setelah container dibuat ulang."
fi
